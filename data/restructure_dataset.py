def split_dataset():
    """Split ntnu_dataset.jsonl into categorized files."""
    data_dir = Path(__file__).resolve().parent
    input_path = data_dir / "ntnu_dataset.jsonl"

    if not input_path.exists():
        print(f"  Input file not found: {input_path}")
        return

    records = []
    with open(input_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                records.append(json.loads(line))

    print(f"  Total records read: {len(records)}")

    output_dir = data_dir / "splits"
    output_dir.mkdir(exist_ok=True)

    categories = {
        "ntnu": "ntnu_general.jsonl",
        "taiwan_geography": "taiwan_geography.jsonl",
        "taiwan_history": "taiwan_history.jsonl",
        "taiwan_politics": "taiwan_politics.jsonl",
        "taiwan_culture": "taiwan_culture.jsonl",
        "taiwan_economy": "taiwan_economy.jsonl",
        "ntnu_misc": "ntnu_extras.jsonl",
    }

    file_handlers = {}
    for cat, filename in categories.items():
        path = output_dir / filename
        file_handlers[cat] = open(path, "w", encoding="utf-8")

    counts = {cat: 0 for cat in categories}
    unclassified = 0

    for record in records:
        cat = classify_record(record)
        if cat in file_handlers:
            file_handlers[cat].write(json.dumps(record, ensure_ascii=False) + "\n")
            counts[cat] += 1
        else:
            file_handlers["ntnu"].write(json.dumps(record, ensure_ascii=False) + "\n")
            unclassified += 1

    for fh in file_handlers.values():
        fh.close()

    print("\n  Classification results:")
    for cat, count in sorted(counts.items()):
        print(f"    {cat}: {count} records")
    if unclassified:
        print(f"    unclassified (→ NTNU): {unclassified}")

    print(f"\n  Files written to: {output_dir}/")
    return records


