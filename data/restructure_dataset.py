def main():
    """Main entry point."""
    print("=" * 60)
    print("Step 1: Splitting ntnu_dataset.jsonl into categories...")
    print("=" * 60)
    split_dataset()

    output_dir = Path(__file__).resolve().parent / "generated"
    output_dir.mkdir(exist_ok=True)

    print("\n" + "=" * 60)
    print("Step 2: Generating Taiwan universities data...")
    print("=" * 60)
    uni_records = generate_all_universities()
    uni_path = output_dir / "taiwan_universities.jsonl"
    with open(uni_path, "w", encoding="utf-8") as f:
        for rec in uni_records:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")
    print(f"  Generated {len(uni_records)} university Q&A records")
    print(f"  Saved to: {uni_path}")

    print("\n" + "=" * 60)
    print("Step 3: Generating Taiwan districts data...")
    print("=" * 60)
    dist_records = generate_districts_data()
    dist_path = output_dir / "taiwan_districts.jsonl"
    with open(dist_path, "w", encoding="utf-8") as f:
        for rec in dist_records:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")
    print(f"  Generated {len(dist_records)} district Q&A records")
    print(f"  Saved to: {dist_path}")

    print("\n" + "=" * 60)
    print("Done! All files have been generated.")
    print("=" * 60)

    # Print stats
    all_outputs = []
    splits_dir = Path(__file__).resolve().parent / "splits"
    if splits_dir.exists():
        all_outputs.extend(sorted(splits_dir.glob("*.jsonl")))
    all_outputs.extend(sorted(output_dir.glob("*.jsonl")))
    print("\nOutput files:")
    for p in all_outputs:
        count = sum(1 for _ in open(p, "r", encoding="utf-8") if _.strip())
        print(f"  {p.name}: {count} records")


if __name__ == "__main__":
    main()
